/**
 * 一个**自绘几何 + 库插值**的图标按钮
 * ============================================================================
 *
 * ## 🔴 而这个文件回答的是"`morphicons` 值不值得加"那一个问题
 *
 * 它是**一次实测**，不是一次集成决定。见
 * `docs/来源记录.md` §6 里那一节的结论与退出条件。
 *
 * ## ⚠️ 而它为什么**不违反**"图形全部自绘"
 *
 * 那条纪律（§1.4 / §4.6.8 的相邻要求）说的是：
 * **不用官方任何素材、图标、文案**。
 *
 * 而 `morphicons` 是**一个插值引擎，不是一套图标**：
 *
 * | 谁提供 | 什么 |
 * |---|---|
 * | **库** | 把两条路径的**三次贝塞尔**对齐、重采样、按弹簧插值 |
 * | **我们** | 那两条路径**本身**（下面的 `MENU` 与 `CLOSE` 是我画的） |
 *
 * 所以"图形自绘"这条**成立** —— 而这句话必须写下来，
 * 因为下一步很容易变成"顺便用它的图标集"。
 *
 * ## 而它给的是 `framer-motion` **做不到**的那一件事
 *
 * `framer-motion` 动画的是 `transform` 与 `opacity`（§7.3 的约束 5 也要求
 * 只用这两样），而它**不插值 SVG 的 `d` 属性**。
 *
 * 而"菜单 → 关闭"这个转场要的正是 `d` 的插值：
 * 三根横线要**连续地**变成那个叉，而不是淡出再淡入。
 *
 * ⚠️ **而这一条是"它解决了别的东西"，不是"我们需要它"。**
 * 我们**现在还没有图标系统** —— 见 `docs/来源记录.md` §6 的退出条件。
 */

import { MorphIcon, type IconNode } from "morphicons/react";

/**
 * 自绘的"菜单"：三根等距横线。
 *
 * ⚠️ **每根线是一个独立的子路径**（`M…h…`），而三条**必须同向**
 *（都是从左到右）—— 一条画反的实现会让插值过程**扭成一团**，
 * 因为库是按点的顺序对齐的。
 */
const MENU: IconNode = [
  ["path", { d: "M4 7h16" }],
  ["path", { d: "M4 12h16" }],
  ["path", { d: "M4 17h16" }],
];

/**
 * 自绘的"关闭"：两条对角线。
 *
 * ⚠️ 而这里有一个**真实的取舍**，它值得写下来：
 *
 * `MENU` 有 3 个子路径，`CLOSE` 有 2 个。而库要做的是把**点集对齐** ——
 * 3 ↔ 2 之间必须有一对"怎么配"。一个"每根线各自找最近的对手"的实现
 * 会给出一个**可接受但不出色**的转场。
 *
 * 所以 `CLOSE` 的写法是**折中过的**：它用两条对角线，而**前两根横线
 * 分别旋向它们** —— 也就是让"3 根 → 2 根"这件事在视觉上读成
 * "外面两根收拢，中间那根跟着上面那根走"。
 *
 * ⚠️ **而这不是我调好的，是它默认行为下看起来对的。**
 * 一个"我要把它调到完美"的实现在这一步会花掉几个小时 ——
 * 而那正是这次实测要判断的成本。
 */
const CLOSE: IconNode = [
  ["path", { d: "M6 6l12 12" }],
  ["path", { d: "M6 18L18 6" }],
];

export interface MorphGlyphProps {
  /** `true` = 画那个叉（关闭态），`false` = 画三根横线。 */
  readonly active: boolean;
  /** 读屏用的名字。**必填** —— 见下。 */
  readonly label: string;
  readonly size?: number;
}

/**
 * 一个会**连续变形**的图标。
 *
 * ## ⚠️ 而 `label` 是必填的，那是这个组件与"画一个 `<span>─</span>`"
 * 最重要的差别
 *
 * 库的文档说得很清楚：
 *
 * > Accessibility: with label → `role="img"` + `<title>`；
 * > without → `aria-hidden`
 *
 * 也就是说**不给 `label` 它就把自己藏起来**。
 * 而一个"装饰性字形当按钮内容"的实现（我上一轮在 `TitleBar` 里就是这么写的）
 * 让读屏用户**只听到"button"** —— 那是 M4 的"读屏通过"那一项里的一个真实缺口。
 */
export function MorphGlyph({ active, label, size = 16 }: MorphGlyphProps): React.ReactElement {
  return (
    <MorphIcon
      icon={active ? CLOSE : MENU}
      size={size}
      strokeWidth={1.5}
      // ⚠️ **`"user"` 而不是库的默认 `"never"`。**
      //
      // 默认值说的是"无论系统的减少动效设置如何都动画" ——
      // 而那与 §7.3 约束 5 的精神相反（那一条要求进度节流、
      // 只动 `transform`/`opacity`，整体的意图是**不要让人难受**）。
      //
      // `"user"` 说的是：系统开了减少动效 ⇒ **瞬间切换**。
      reducedMotion="user"
      label={label}
    />
  );
}

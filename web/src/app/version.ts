/**
 * 应用版本号 —— **界面上唯一的那一份**（`docs/UI设计规格.md` §4.6.1 的下段）
 * ============================================================================
 *
 * ## 它出现在两处，而两处必须是同一个数
 *
 * | 位置 | 出处 |
 * |---|---|
 * | 侧栏下段的最后一行 | §4.6.1 的四段结构：`账号管理 / 百宝箱 / 设置 / 关于` 之后是版本号 |
 * | 状态条的第一项（常驻） | §4.1 的状态条：常驻四项 = 版本 / 当前产品 / 源 / 网速 |
 *
 * ## 🔴 而"这个数是什么"今天有三个地方写着它
 *
 * ```text
 *   package.json:4              "version": "0.0.0"   ← 前端包
 *   src-tauri/tauri.conf.json:4 "version": "0.0.0"   ← 装出来的那个 exe（安装包叫 秦墨_0.0.0_x64-setup.exe）
 *   web/src/app/version.ts      APP_VERSION = "0.0.0" ← 界面显示的那个
 * ```
 *
 * ⚠️ **所以这一份是"抄"来的**，而"抄"如果没有东西盯着，总有一天会不同步 ——
 * 那时界面上写着 `v0.0.0` 而装出来的包是 `0.1.0`，**没有任何检查会红**。
 *
 * 所以 `tools/check-shell-contract.ps1` 有一条：**这三处逐字相同**。
 * 一个更好的做法是让内核把它报上来（`qul-core` 的 `about.version` 那条
 * 本地化文案就是这么用的），而那要等"实例域纵线"接真内核那一轮 ——
 * 到那时这个文件变成那个命令的**兜底**，而那条检查继续钉着三处一致。
 *
 * ## ⚠️ 而它不是"规格稿里的 `v0.1.0`"
 *
 * §4.6.1 的 ASCII 骨架里写着 `v0.1.0`，那是**稿子里的示意**。
 * §4.6.1.3 的文案纪律说界面上只能有**事实性占位**，
 * 而"事实"就是 `package.json` / `tauri.conf.json` 里的那个值。
 */


export interface RailIconProps {
  readonly name: RailIconName;
  /** 边长，CSS px。默认 20（§4.4 的"卡片内 16–20 px"）。 */
  readonly size?: number;
}

/**
 * 画一个导航图形。
 *
 * ⚠️ **`width` / `height` 是属性而不是 CSS**：图形的尺寸在**这里**给出来，
 * 于是"这个图标多大"在一个地方读得出来。若交给 CSS 的 `.shell__railGlyph`，
 * 那么"窄栏 20 px、宽栏也可能是 20 px"这件事就得靠继承来猜，
 * 而 SVG 的默认尺寸是 300 × 150 —— 漏一条规则就是满屏的一个巨形图标。
 */
export function RailIcon({ name, size = 20 }: RailIconProps): ReactElement {
  return (
    <svg
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fill="none"
      stroke="currentColor"
      strokeWidth="1.5"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      {RAIL_ICON_PATHS[name].map((d) => (
        <path key={d} d={d} />
      ))}
    </svg>
  );
}
